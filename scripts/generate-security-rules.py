#!/usr/bin/env python3
"""Generate provider-neutral security rules from canonical policy IDs."""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path
from typing import Any

from registry_lib import (
    PROJECTED_POLICY_RENDER_FIELDS,
    ROOT,
    agent_rule_set_policy_ids,
    normalized_node_digest,
    resolve_policy_ids,
    validate_projected_policy_node,
    write_text,
)


GENERATED_MARKER = "<!-- Generated by scripts/generate-security-rules.py from registry/policies.yaml. Do not edit. -->"
SUMMARY_FIELDS = {"ecosystems", "enforcement", "group", "id", "risk", "title"}
APPLICABILITY_FIELDS = {"applicability", "applies_when", "paths", "selectors"}
REQUIREMENT_FIELDS = {
    "decision",
    "default_age_days",
    "description",
    "failure_behavior",
    "match_handling",
    "preflight_must_verify",
    "required_guarantees",
    "requirements",
    "selection_order",
    "threshold_hours",
    "time_basis",
}
VERIFICATION_FIELDS = {"verification"}
CONTROL_FIELDS = {
    "access_gate",
    "apply_gate",
    "change_gate",
    "deployment_gate",
    "escalation",
    "exception",
    "limitation",
    "non_triggers",
    "production_gate",
    "production_or_destructive_gate",
    "review_requirement",
    "runtime_backstops",
    "runtime_requirement",
    "triggers",
    "trust_boundary",
}
RENDERED_POLICY_FIELDS = frozenset(
    SUMMARY_FIELDS
    | APPLICABILITY_FIELDS
    | REQUIREMENT_FIELDS
    | VERIFICATION_FIELDS
    | CONTROL_FIELDS
)
if RENDERED_POLICY_FIELDS != PROJECTED_POLICY_RENDER_FIELDS:
    raise RuntimeError("projected policy field renderer coverage is incomplete")


def _string_list(value: Any) -> list[str]:
    """Return non-empty string items from a possible list.

    Args:
        value: Parsed registry value.

    Returns:
        Non-empty string list.
    """
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, str) and item]


def _format_scalar(value: Any) -> str:
    """Render a canonical scalar consistently.

    Args:
        value: Parsed scalar value.

    Returns:
        Compact scalar text.
    """
    if value is None:
        return "none"
    if isinstance(value, bool):
        return str(value).lower()
    return str(value)


def _render_structured_field(value: Any, prefix: str) -> list[str]:
    """Render structured canonical data without numeric list indices.

    Args:
        value: Parsed mapping, list, or scalar.
        prefix: Dotted field path accumulated during recursion.

    Returns:
        Deterministic Markdown lines retaining every scalar leaf.
    """
    lines: list[str] = []
    if isinstance(value, dict):
        if not value:
            return [f"- **{prefix}:** none"]
        for key in sorted(value):
            child_prefix = f"{prefix}.{key}" if prefix else str(key)
            lines.extend(_render_structured_field(value[key], child_prefix))
    elif isinstance(value, list):
        if not value:
            return [f"- **{prefix}:** none"]
        lines.append(f"- **{prefix}:**")
        lines.extend(f"  - {_format_scalar(item)}" for item in value)
    else:
        lines.append(f"- **{prefix}:** {_format_scalar(value)}")
    return lines


def _render_selector_value(value: Any, path: str, indentation: str) -> list[str]:
    """Render one selector value with deterministic paths and nesting.

    Args:
        value: Canonical selector value.
        path: Dotted and indexed canonical selector path.
        indentation: Markdown indentation for the current path.

    Returns:
        Markdown lines for the current selector value and every descendant.
    """
    if isinstance(value, dict):
        if not value:
            return [f"{indentation}- **{path}:** none"]
        lines = [f"{indentation}- **{path}:**"]
        for field_name in sorted(value):
            child_path = f"{path}.{field_name}"
            lines.extend(_render_selector_value(value[field_name], child_path, f"{indentation}  "))
        return lines
    if isinstance(value, list):
        if not value:
            return [f"{indentation}- **{path}:** none"]
        lines = [f"{indentation}- **{path}:**"]
        for item_index, item in enumerate(value):
            lines.extend(
                _render_selector_value(item, f"{path}[{item_index}]", f"{indentation}  ")
            )
        return lines
    return [f"{indentation}- **{path}:** {_format_scalar(value)}"]


def _render_selector_groups(selectors: Any) -> list[str]:
    """Render selectors recursively without losing parent-row association.

    Args:
        selectors: Canonical selector list.

    Returns:
        Grouped selector lines with explicit dotted and indexed paths.
    """
    return _render_selector_value(selectors, "selectors", "")


def _field_lines(policy_node: dict[str, Any], field_names: set[str]) -> list[str]:
    """Render complete canonical fields without dropping nested policy data.

    Args:
        policy_node: Canonical policy node.
        field_names: Top-level fields assigned to the rendered section.

    Returns:
        Deterministically grouped field lines.
    """
    lines: list[str] = []
    for field_name in sorted(field_names & set(policy_node)):
        if field_name == "selectors":
            lines.extend(_render_selector_groups(policy_node[field_name]))
        else:
            lines.extend(_render_structured_field(policy_node[field_name], field_name))
    return lines


def _render_section(policy_node: dict[str, Any], field_names: set[str]) -> str:
    """Render a policy section with meaningful absence made explicit.

    Args:
        policy_node: Canonical policy node.
        field_names: Top-level fields assigned to the rendered section.

    Returns:
        Markdown body for the section.
    """
    lines = _field_lines(policy_node, field_names)
    return "\n".join(lines) if lines else "- none"


def _render_policy(policy_id: str, policy_node: dict[str, Any]) -> str:
    """Render one canonical policy node for agent consumption.

    Args:
        policy_id: Stable canonical policy ID.
        policy_node: Resolved canonical policy node.
    Returns:
        Markdown policy section.
    """
    validate_projected_policy_node(policy_id, policy_node)
    title = _format_scalar(policy_node.get("title"))
    group = _format_scalar(policy_node.get("group"))
    risk = _format_scalar(policy_node.get("risk"))
    enforcement = _format_scalar(policy_node.get("enforcement"))
    ecosystems = _string_list(policy_node.get("ecosystems"))
    ecosystem_text = ", ".join(ecosystems) if ecosystems else "none"
    digest = normalized_node_digest(policy_node)
    return "\n".join(
        [
            f"## `{policy_id}`",
            "",
            (
                f"**ID:** `{policy_id}` | **Title:** {title} | **Group:** {group} | "
                f"**Risk:** `{risk}` | **Enforcement:** `{enforcement}` | "
                f"**Ecosystems:** {ecosystem_text} | **Digest:** `{digest}`"
            ),
            "",
            "### Applicability",
            "",
            _render_section(policy_node, APPLICABILITY_FIELDS),
            "",
            "### Requirements",
            "",
            _render_section(policy_node, REQUIREMENT_FIELDS),
            "",
            "### Verification",
            "",
            _render_section(policy_node, VERIFICATION_FIELDS),
            "",
            "### Escalation, exceptions, gates, and limitations",
            "",
            _render_section(policy_node, CONTROL_FIELDS),
        ]
    )


def _render_enforcement_legend(classifications: dict[str, Any]) -> str:
    """Render the single enforcement-classification legend.

    Args:
        classifications: Canonical enforcement classification descriptions.

    Returns:
        Compact Markdown legend.
    """
    lines = ["## Enforcement legend", ""]
    for classification_name in sorted(classifications):
        classification = classifications[classification_name]
        description = classification.get("description") if isinstance(classification, dict) else None
        lines.append(f"- `{classification_name}`: {_format_scalar(description)}")
    return "\n".join(lines)


def _render_rule_file(
    title: str,
    policy_ids: list[str],
    policy_nodes: dict[str, dict[str, Any]],
    classifications: dict[str, Any],
    focused: bool,
) -> str:
    """Render a universal or focused rule file.

    Args:
        title: Artifact title.
        policy_ids: Ordered source policy IDs.
        policy_nodes: Resolved canonical policy nodes.
        classifications: Enforcement classification descriptions.
        focused: Whether to reference the universal set first.

    Returns:
        Complete Markdown artifact.
    """
    introduction = (
        "Load `../universal.md` first. It remains in force and is referenced rather than duplicated here."
        if focused
        else "Load this universal rule set before any situation-specific language or tool rule set."
    )
    sections = [
        GENERATED_MARKER,
        "",
        f"# {title}",
        "",
        introduction,
    ]
    if not focused:
        sections.extend(["", _render_enforcement_legend(classifications)])
    for policy_id in policy_ids:
        sections.extend(["", _render_policy(policy_id, policy_nodes[policy_id])])
    return "\n".join(sections)


def _render_index(
    title: str,
    section_name: str,
    groups: dict[str, list[str]],
) -> str:
    """Render a deterministic language or tool rule index.

    Args:
        title: Index title.
        section_name: Projection section name.
        groups: Group-to-policy-ID mapping.
    Returns:
        Complete Markdown index.
    """
    lines = [
        GENERATED_MARKER,
        "",
        f"# {title}",
        "",
        "Load `../universal.md` before loading the union of every matching focused set.",
        "",
        "## Rule sets",
        "",
    ]
    for group_name in sorted(groups):
        source_ids = ", ".join(f"`{policy_id}`" for policy_id in groups[group_name])
        lines.append(f"- [`{group_name}`]({group_name}.md) — {source_ids}")
    return "\n".join(lines)


def _render_routing_index(
    projection: dict[str, Any],
) -> str:
    """Render the compact provider-neutral routing contract.

    Args:
        projection: Canonical rule-set projection metadata.
    Returns:
        Complete master routing Markdown.
    """
    return "\n".join(
        [
            GENERATED_MARKER,
            "",
            "# Security Rule Routing",
            "",
            "1. Load [`rules/universal.md`](rules/universal.md) first.",
            "2. Derive repository-relative affected paths and observed ecosystems from trusted task context.",
            "3. Add semantic conditions only when a trusted content-aware validator establishes them; filenames are not semantic proof.",
            "4. Load the union of every matching [language](rules/languages/index.md) and [tool](rules/tools/index.md) set using any-match path, ecosystem, or semantic selectors.",
            f"5. If an observed toolchain is unknown, load the fallback [`{projection['unknown_tool_fallback']}`](rules/{projection['unknown_tool_fallback']}.md).",
            "6. Treat matched rule-set risk and enforcement metadata as potential, not an action-specific approval result. This router does not evaluate gates, including universal rules. Determine the proposed action and verified effect before applying every applicable safeguard; never waive an active gate.",
            "7. Credential-bearing selectors identify sensitive files only. Do not read values by default, and never log, persist, or place values in prompts or generated artifacts.",
            "",
            "This layer routes canonical requirements; `registry/policies.yaml` remains the sole source of policy prose.",
            "Generated text reports canonical controls and limitations; it does not implement or prove runtime enforcement.",
        ]
    )


def generate_security_rules(policies: dict[str, Any], output_root: Path) -> None:
    """Generate all security rule files beneath an output root.

    Args:
        policies: Parsed canonical policies registry.
        output_root: Root containing the generated ``security`` directory.
    """
    secure_policy = policies.get("secure_sdd_policy", {})
    projection = secure_policy.get("agent_rule_sets", {}) if isinstance(secure_policy, dict) else {}
    if not isinstance(projection, dict):
        raise ValueError("secure_sdd_policy.agent_rule_sets must be a mapping")
    policy_nodes = resolve_policy_ids(policies, agent_rule_set_policy_ids(projection))
    for policy_id, policy_node in policy_nodes.items():
        validate_projected_policy_node(policy_id, policy_node)
    classifications = secure_policy.get("enforcement_model", {}).get("classifications", {})
    security_directory = output_root / "security"
    rules_directory = security_directory / "rules"
    if rules_directory.exists():
        shutil.rmtree(rules_directory)

    write_text(security_directory / "rules.md", _render_routing_index(projection))
    universal_policy_ids = projection["universal"]
    write_text(
        rules_directory / "universal.md",
        _render_rule_file(
            "Universal Security Rules",
            universal_policy_ids,
            policy_nodes,
            classifications,
            focused=False,
        ),
    )
    for section_name, title in (("languages", "Language Security Rules"), ("tools", "Tool Security Rules")):
        groups = projection[section_name]
        write_text(
            rules_directory / section_name / "index.md",
            _render_index(title, section_name, groups),
        )
        for group_name in sorted(groups):
            write_text(
                rules_directory / section_name / f"{group_name}.md",
                _render_rule_file(
                    f"{group_name.replace('_', ' ').title()} Security Rules",
                    groups[group_name],
                    policy_nodes,
                    classifications,
                    focused=True,
                ),
            )


def main() -> int:
    """Generate tracked security rule artifacts.

    Returns:
        Process exit code.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-root",
        type=Path,
        default=ROOT,
        help="Root beneath which security rule artifacts are generated.",
    )
    arguments = parser.parse_args()
    from registry_lib import load_registry

    policies = load_registry("policies")
    generate_security_rules(policies, arguments.output_root.resolve())
    print(f"Generated security rules under {arguments.output_root.resolve() / 'security'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
