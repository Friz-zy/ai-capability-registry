#!/usr/bin/env python3
"""Generate provider-neutral security rules from canonical policy IDs."""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path
from typing import Any

from registry_lib import (
    PROJECTED_POLICY_RENDER_FIELDS,
    ROOT,
    agent_rule_set_policy_ids,
    normalized_node_digest,
    resolve_policy_ids,
    validate_projected_policy_node,
    write_text,
)


GENERATED_MARKER = "<!-- Generated by scripts/generate-security-rules.py from registry/policies.yaml. Do not edit. -->"
SUMMARY_FIELDS = {"ecosystems", "enforcement", "group", "id", "risk", "title"}
APPLICABILITY_FIELDS = {"applicability", "applies_when", "paths", "selectors"}
REQUIREMENT_FIELDS = {
    "decision",
    "default_age_days",
    "description",
    "failure_behavior",
    "match_handling",
    "preflight_must_verify",
    "required_guarantees",
    "requirements",
    "selection_order",
    "threshold_hours",
    "time_basis",
}
VERIFICATION_FIELDS = {"verification"}
CONTROL_FIELDS = {
    "access_gate",
    "apply_gate",
    "change_gate",
    "deployment_gate",
    "escalation",
    "exception",
    "limitation",
    "non_triggers",
    "production_gate",
    "production_or_destructive_gate",
    "review_requirement",
    "runtime_backstops",
    "runtime_requirement",
    "triggers",
    "trust_boundary",
}
RENDERED_POLICY_FIELDS = frozenset(
    SUMMARY_FIELDS
    | APPLICABILITY_FIELDS
    | REQUIREMENT_FIELDS
    | VERIFICATION_FIELDS
    | CONTROL_FIELDS
)
if RENDERED_POLICY_FIELDS != PROJECTED_POLICY_RENDER_FIELDS:
    raise RuntimeError("projected policy field renderer coverage is incomplete")


def _string_list(value: Any) -> list[str]:
    """Return non-empty string items from a possible list.

    Args:
        value: Parsed registry value.

    Returns:
        Non-empty string list.
    """
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, str) and item]


def _bullets(values: list[str], empty_text: str = "None declared.") -> str:
    """Render Markdown bullets with an explicit empty value.

    Args:
        values: Values to render.
        empty_text: Text used when no values exist.

    Returns:
        Markdown bullet text.
    """
    if not values:
        return f"- {empty_text}"
    return "\n".join(f"- {value}" for value in values)


def _flatten_mapping(value: Any, prefix: str = "") -> list[str]:
    """Flatten structured policy requirements into readable deterministic lines.

    Args:
        value: Parsed mapping, list, or scalar.
        prefix: Dotted field path accumulated during recursion.

    Returns:
        Flattened requirement descriptions.
    """
    flattened: list[str] = []
    if isinstance(value, dict):
        if not value:
            return [f"{prefix}: {{}}" if prefix else "{}"]
        for key in sorted(value):
            child_prefix = f"{prefix}.{key}" if prefix else str(key)
            flattened.extend(_flatten_mapping(value[key], child_prefix))
    elif isinstance(value, list):
        if not value:
            return [f"{prefix}: []" if prefix else "[]"]
        for index, item in enumerate(value):
            item_prefix = f"{prefix}[{index}]" if prefix else f"[{index}]"
            if isinstance(item, (dict, list)):
                flattened.extend(_flatten_mapping(item, item_prefix))
            else:
                flattened.append(f"{item_prefix}: {item}")
    elif value is None:
        flattened.append(f"{prefix}: null" if prefix else "null")
    else:
        flattened.append(f"{prefix}: {value}" if prefix else str(value))
    return flattened


def _source_metadata(policy_ids: list[str], policy_nodes: dict[str, dict[str, Any]]) -> str:
    """Render source IDs and normalized-node digests.

    Args:
        policy_ids: Ordered policy IDs represented by an artifact.
        policy_nodes: Resolved canonical nodes keyed by ID.

    Returns:
        Markdown source metadata table.
    """
    rows = ["| Policy ID | Normalized-node SHA-256 |", "| --- | --- |"]
    rows.extend(
        f"| `{policy_id}` | `{normalized_node_digest(policy_nodes[policy_id])}` |"
        for policy_id in policy_ids
    )
    return "\n".join(rows)


def _field_lines(policy_node: dict[str, Any], field_names: set[str]) -> list[str]:
    """Render complete canonical fields without dropping nested policy data.

    Args:
        policy_node: Canonical policy node.
        field_names: Top-level fields assigned to the rendered section.

    Returns:
        Deterministically flattened field lines.
    """
    lines: list[str] = []
    for field_name in sorted(field_names & set(policy_node)):
        lines.extend(_flatten_mapping(policy_node[field_name], field_name))
    return lines


def _render_policy(policy_id: str, policy_node: dict[str, Any], classifications: dict[str, Any]) -> str:
    """Render one canonical policy node for agent consumption.

    Args:
        policy_id: Stable canonical policy ID.
        policy_node: Resolved canonical policy node.
        classifications: Enforcement classification descriptions.

    Returns:
        Markdown policy section.
    """
    validate_projected_policy_node(policy_id, policy_node)
    title = policy_node.get("title") or policy_node.get("group") or policy_id
    risk = policy_node.get("risk", "Inherited from the canonical risk model")
    enforcement = policy_node.get("enforcement", "See declared gates")
    classification = classifications.get(enforcement, {}) if isinstance(classifications, dict) else {}
    classification_description = classification.get("description") if isinstance(classification, dict) else None
    enforcement_text = f"`{enforcement}`"
    if isinstance(classification_description, str):
        enforcement_text += f" — {classification_description}"
    ecosystems = _string_list(policy_node.get("ecosystems"))
    return "\n".join(
        [
            f"## {title}",
            "",
            f"- **Policy ID:** `{policy_id}`",
            f"- **Risk:** `{risk}`",
            f"- **Enforcement classification:** {enforcement_text}",
            f"- **Ecosystems:** {', '.join(f'`{value}`' for value in ecosystems) if ecosystems else 'Universal or not separately declared.'}",
            "",
            "### Applicability",
            "",
            _bullets(_field_lines(policy_node, APPLICABILITY_FIELDS)),
            "",
            "### Requirements",
            "",
            _bullets(_field_lines(policy_node, REQUIREMENT_FIELDS)),
            "",
            "### Verification",
            "",
            _bullets(_field_lines(policy_node, VERIFICATION_FIELDS)),
            "",
            "### Escalation, exceptions, gates, and limitations",
            "",
            _bullets(_field_lines(policy_node, CONTROL_FIELDS)),
        ]
    )


def _render_rule_file(
    title: str,
    policy_ids: list[str],
    policy_nodes: dict[str, dict[str, Any]],
    classifications: dict[str, Any],
    focused: bool,
) -> str:
    """Render a universal or focused rule file.

    Args:
        title: Artifact title.
        policy_ids: Ordered source policy IDs.
        policy_nodes: Resolved canonical policy nodes.
        classifications: Enforcement classification descriptions.
        focused: Whether to reference the universal set first.

    Returns:
        Complete Markdown artifact.
    """
    introduction = (
        "Load `../universal.md` first. It remains in force and is referenced rather than duplicated here."
        if focused
        else "Load this universal rule set before any situation-specific language or tool rule set."
    )
    sections = [
        GENERATED_MARKER,
        "",
        f"# {title}",
        "",
        introduction,
        "",
        "## Canonical sources",
        "",
        _source_metadata(policy_ids, policy_nodes),
    ]
    for policy_id in policy_ids:
        sections.extend(["", _render_policy(policy_id, policy_nodes[policy_id], classifications)])
    return "\n".join(sections)


def _render_index(
    title: str,
    section_name: str,
    groups: dict[str, list[str]],
    policy_nodes: dict[str, dict[str, Any]],
) -> str:
    """Render a deterministic language or tool rule index.

    Args:
        title: Index title.
        section_name: Projection section name.
        groups: Group-to-policy-ID mapping.
        policy_nodes: Resolved canonical policy nodes.

    Returns:
        Complete Markdown index.
    """
    policy_ids = [policy_id for group_name in sorted(groups) for policy_id in groups[group_name]]
    lines = [
        GENERATED_MARKER,
        "",
        f"# {title}",
        "",
        "Load `../universal.md` before loading the union of every matching focused set.",
        "",
        "## Rule sets",
        "",
    ]
    for group_name in sorted(groups):
        source_ids = ", ".join(f"`{policy_id}`" for policy_id in groups[group_name])
        lines.append(f"- [`{group_name}`]({group_name}.md) — {source_ids}")
    lines.extend(["", "## Canonical sources", "", _source_metadata(policy_ids, policy_nodes)])
    return "\n".join(lines)


def _render_routing_index(
    projection: dict[str, Any],
    policy_nodes: dict[str, dict[str, Any]],
) -> str:
    """Render the compact provider-neutral routing contract.

    Args:
        projection: Canonical rule-set projection metadata.
        policy_nodes: Resolved canonical policy nodes.

    Returns:
        Complete master routing Markdown.
    """
    policy_ids = agent_rule_set_policy_ids(projection)
    return "\n".join(
        [
            GENERATED_MARKER,
            "",
            "# Security Rule Routing",
            "",
            "1. Load [`rules/universal.md`](rules/universal.md) first.",
            "2. Derive repository-relative affected paths and observed ecosystems from trusted task context.",
            "3. Add semantic conditions only when a trusted content-aware validator establishes them; filenames are not semantic proof.",
            "4. Load the union of every matching [language](rules/languages/index.md) and [tool](rules/tools/index.md) set using any-match path, ecosystem, or semantic selectors.",
            f"5. If an observed toolchain is unknown, load the fallback [`{projection['unknown_tool_fallback']}`](rules/{projection['unknown_tool_fallback']}.md).",
            "6. Apply the highest risk and the union of all enforcement classifications and human/runtime gates across matching focused policies; never lower, omit, or waive them without canonical authorization.",
            "7. Credential-bearing selectors identify sensitive files only. Do not read values by default, and never log, persist, or place values in prompts or generated artifacts.",
            "",
            "This layer routes canonical requirements; `registry/policies.yaml` remains the sole source of policy prose.",
            "Generated text reports canonical controls and limitations; it does not implement or prove runtime enforcement.",
            "",
            "## Canonical sources",
            "",
            _source_metadata(policy_ids, policy_nodes),
        ]
    )


def generate_security_rules(policies: dict[str, Any], output_root: Path) -> None:
    """Generate all security rule files beneath an output root.

    Args:
        policies: Parsed canonical policies registry.
        output_root: Root containing the generated ``security`` directory.
    """
    secure_policy = policies.get("secure_sdd_policy", {})
    projection = secure_policy.get("agent_rule_sets", {}) if isinstance(secure_policy, dict) else {}
    if not isinstance(projection, dict):
        raise ValueError("secure_sdd_policy.agent_rule_sets must be a mapping")
    policy_nodes = resolve_policy_ids(policies, agent_rule_set_policy_ids(projection))
    for policy_id, policy_node in policy_nodes.items():
        validate_projected_policy_node(policy_id, policy_node)
    classifications = secure_policy.get("enforcement_model", {}).get("classifications", {})
    security_directory = output_root / "security"
    rules_directory = security_directory / "rules"
    if rules_directory.exists():
        shutil.rmtree(rules_directory)

    write_text(security_directory / "rules.md", _render_routing_index(projection, policy_nodes))
    universal_policy_ids = projection["universal"]
    write_text(
        rules_directory / "universal.md",
        _render_rule_file(
            "Universal Security Rules",
            universal_policy_ids,
            policy_nodes,
            classifications,
            focused=False,
        ),
    )
    for section_name, title in (("languages", "Language Security Rules"), ("tools", "Tool Security Rules")):
        groups = projection[section_name]
        write_text(
            rules_directory / section_name / "index.md",
            _render_index(title, section_name, groups, policy_nodes),
        )
        for group_name in sorted(groups):
            write_text(
                rules_directory / section_name / f"{group_name}.md",
                _render_rule_file(
                    f"{group_name.replace('_', ' ').title()} Security Rules",
                    groups[group_name],
                    policy_nodes,
                    classifications,
                    focused=True,
                ),
            )


def main() -> int:
    """Generate tracked security rule artifacts.

    Returns:
        Process exit code.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-root",
        type=Path,
        default=ROOT,
        help="Root beneath which security rule artifacts are generated.",
    )
    arguments = parser.parse_args()
    from registry_lib import load_registry

    policies = load_registry("policies")
    generate_security_rules(policies, arguments.output_root.resolve())
    print(f"Generated security rules under {arguments.output_root.resolve() / 'security'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
